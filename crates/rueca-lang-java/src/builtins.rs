//! Names the resolver must never fuzzy-match to project symbols.
//!
//! - **`java.lang`** types, implicitly imported by every compilation unit
//!   (Java SE 21), plus the package heads of the JDK (`java`, `javax`,
//!   `jakarta`, `jdk`, `sun`) so that fully qualified uses
//!   (`java.util.Objects.hash(…)`) stop as external.
//! - **Common JDK types** of `java.util`, `java.util.function`,
//!   `java.util.stream`, `java.util.concurrent`, `java.io`, `java.nio.file`,
//!   `java.math`, `java.time`, `java.lang.reflect` and
//!   `java.lang.annotation`. They are imported (explicitly or on demand)
//!   from outside the project, so a reference that reaches the unique-name
//!   rung is a JDK use, never a project symbol. Project types with the same
//!   name are still found first through imports and the package.
//! - **Methods every object or JDK collection / stream / string has**
//!   (`toString`, `equals`, `size`, `stream`, …): the resolver's
//!   unique-method rung would otherwise link every `list.stream()` on an
//!   untyped receiver to the only project method named `stream`. Typed
//!   receivers (`$type:T`) and implicit `this` still resolve them.
//!
//! Sorted for binary search (checked by a test).

