//!   `kotlin.ranges.*`, `kotlin.sequences.*`, `kotlin.text.*` and (on the
//!   JVM) `java.lang.*` and `kotlin.jvm.*`, plus common JDK types and the
//!   package heads (`kotlin`, `kotlinx`, `java`, `javax`, `jakarta`,
//!   `android`, `androidx`, `jdk`, `sun`) so that fully qualified uses stop
//!   as external.
//! - **Standard-library functions** every file sees without an import
//!   (`listOf`, `require`, `println`, the scope functions `let` / `apply` /
//!   `run` / `also` / `with`, …).
