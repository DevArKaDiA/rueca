//! Backward compatibility of the segment format across additive model
//! changes.
//!
//! `tests/fixtures/segment-v2-pre-wave-r/` is a store written by the build
//! *before* RFC 0003 wave R appended variants to `Language`, `Label`,
//! `RefKind` and `Strategy` (commit 3d670ea, segment format 2). It uses
//! every variant that existed then. Appending variants must keep it
//! readable with identical tables, adjacency and search; only a
//! [`FORMAT_VERSION`] bump may retire it (then this test must expect
//! `SegmentError::Version` instead).
//!
//! The fixture was generated with
//! `RUECA_COMPAT_OUT=<dir> cargo test -p rueca-segment --test compat write_fixture -- --ignored`
//! at that commit; it is not regenerated by later builds.

use std::collections::HashMap;
use std::path::{Path, PathBuf};

use rueca_model::{
    Edge, EdgeKind, EdgeMeta, FileEntry, Label, Language, Node, ResolvedGraph, SnapshotInfo, Span, Strategy,
    git_blob_sha,
};
use rueca_segment::{ContentSource, FORMAT_VERSION, Segment, SegmentError, SymbolQuery, write_segment};

struct Mem(HashMap<String, Vec<u8>>);

impl ContentSource for Mem {
    fn content(&self, file: &FileEntry) -> std::io::Result<Vec<u8>> {
        self.0.get(&file.path).cloned().ok_or_else(|| std::io::Error::other(file.path.clone()))
    }
}

/// Every `Language`, `Label`, `EdgeKind` and `Strategy` variant of segment
/// format 2 before wave R, in declaration order.
const LANGUAGES: [Language; 6] =
    [Language::Python, Language::JavaScript, Language::TypeScript, Language::Tsx, Language::Php, Language::Markdown];
const SYMBOL_LABELS: [Label; 19] = [
    Label::Module,
    Label::Package,
    Label::Function,
    Label::Method,
    Label::Class,
    Label::Interface,
    Label::Trait,
    Label::Struct,
    Label::Enum,
    Label::TypeAlias,
    Label::Field,
    Label::Variable,
    Label::Constant,
    Label::Route,
    Label::RpcMethod,
    Label::Topic,
    Label::EnvVar,
    Label::Test,
    Label::Section,
];
const EDGE_KINDS: [EdgeKind; 13] = [
    EdgeKind::Contains,
    EdgeKind::Defines,
    EdgeKind::Imports,
    EdgeKind::Calls,
    EdgeKind::References,
    EdgeKind::Inherits,
    EdgeKind::Implements,
    EdgeKind::Overrides,
    EdgeKind::Decorates,
    EdgeKind::Reads,
    EdgeKind::Writes,
    EdgeKind::Throws,
    EdgeKind::Tests,
];
const STRATEGIES: [Strategy; 7] = [
    Strategy::Syntactic,
    Strategy::Scip,
    Strategy::TypeResolved,
    Strategy::ImportResolved,
    Strategy::SameModule,
    Strategy::UniqueName,
    Strategy::Heuristic,
];

fn span(line: u32) -> Span {
    Span {
        start_byte: line * 20,
        end_byte: line * 20 + 15,
        start_line: line,
        start_col: 0,
        end_line: line,
        end_col: 15,
    }
}

fn graph() -> (ResolvedGraph, Mem) {
    let ext = ["py", "js", "ts", "tsx", "php", "md"];
    let mut nodes = vec![
        Node {
            label: Label::Repository,
            name: "compat".into(),
            qualified_name: "local/compat".into(),
            file: None,
            span: None,
            language: None,
            signature: None,
            doc: None,
            exported: false,
            is_test: false,
        },
        Node {
            label: Label::Folder,
            name: "src".into(),
            qualified_name: "src".into(),
            file: None,
            span: None,
            language: None,
            signature: None,
            doc: None,
            exported: false,
            is_test: false,
        },
    ];
    let mut files = Vec::new();
    let mut contents = HashMap::new();
    for (i, (lang, e)) in LANGUAGES.iter().zip(ext).enumerate() {
        let path = format!("src/m{i}.{e}");
        let body: String = (0..20).map(|l| format!("compat_symbol_{l:<5}\n")).collect();
        files.push(FileEntry {
            path: path.clone(),
            blob_sha: git_blob_sha(body.as_bytes()),
            language: Some(*lang),
            size: body.len() as u64,
            line_count: 20,
            node: nodes.len() as u32,
            status: "ok".into(),
        });
        nodes.push(Node {
            label: Label::File,
            name: format!("m{i}.{e}"),
            qualified_name: path.clone(),
            file: Some(i as u32),
            span: None,
            language: Some(*lang),
            signature: None,
            doc: None,
            exported: false,
            is_test: false,
        });
        contents.insert(path, body.into_bytes());
    }
    let first_symbol = nodes.len() as u32;
    for (k, label) in SYMBOL_LABELS.iter().enumerate() {
        let f = k % LANGUAGES.len();
        nodes.push(Node {
            label: *label,
            name: format!("compat{label}"),
            qualified_name: format!("m{f}:compat{label}"),
            file: Some(f as u32),
            span: Some(span(k as u32)),
            language: Some(LANGUAGES[f]),
            signature: Some(format!("{label} compat{label}")),
            doc: (k % 2 == 0).then(|| format!("doc of {label}")),
            exported: k % 3 != 0,
            is_test: *label == Label::Test,
        });
    }
    let mut edges = vec![Edge {
        src: 0,
        dst: 1,
        kind: EdgeKind::Contains,
        meta: EdgeMeta { confidence: 1.0, strategy: Strategy::Syntactic, evidence: None },
    }];
    let n_sym = SYMBOL_LABELS.len() as u32;
    for (k, kind) in EDGE_KINDS.iter().enumerate() {
        for (s, strategy) in STRATEGIES.iter().enumerate() {
            let src = first_symbol + (k as u32 * 3 + s as u32) % n_sym;
            let dst = first_symbol + (k as u32 + 5 * s as u32 + 1) % n_sym;
            if src == dst {
                continue;
            }
            let evidence = (s % 2 == 1).then(|| (nodes[src as usize].file.unwrap(), span(s as u32)));
            edges.push(Edge {
                src,
                dst,
                kind: *kind,
                meta: EdgeMeta { confidence: 0.5 + s as f32 / 20.0, strategy: *strategy, evidence },
            });
        }
    }
    edges.sort_by_key(|e| (e.src, e.kind, e.dst));
    edges.dedup_by_key(|e| (e.src, e.kind, e.dst));
    let snapshot = SnapshotInfo {
        repo: "local/compat".into(),
        commit: "3d670ea".into(),
        dirty: false,
        branch: None,
        root: Some("/compat".into()),
        indexed_at: 0,
        rueca_version: "0.1.0-alpha.1".into(),
    };
    (ResolvedGraph { snapshot, nodes, edges, files, modules: vec![] }, Mem(contents))
}

fn fixture_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/segment-v2-pre-wave-r")
}

fn copy_dir(from: &Path, to: &Path) {
    std::fs::create_dir_all(to).unwrap();
    for e in std::fs::read_dir(from).unwrap() {
        let e = e.unwrap();
        let target = to.join(e.file_name());
        if e.file_type().unwrap().is_dir() {
            copy_dir(&e.path(), &target);
        } else {
            std::fs::copy(e.path(), target).unwrap();
        }
    }
}

#[test]
#[ignore = "generates the fixture; run only at the pre-wave-R commit"]
fn write_fixture() {
    let out = PathBuf::from(std::env::var("RUECA_COMPAT_OUT").expect("RUECA_COMPAT_OUT"));
    let (graph, mem) = graph();
    write_segment(&graph, &mem, &out).unwrap();
}

#[test]
fn segment_written_before_wave_r_opens_unchanged() {
    let tmp = tempfile::tempdir().unwrap();
    copy_dir(&fixture_dir(), tmp.path());
    let seg_dir = tmp.path().join("segments");
    let seg_path = std::fs::read_dir(&seg_dir)
        .unwrap()
        .map(|e| e.unwrap().path())
        .find(|p| p.extension().is_some_and(|e| e == "rcseg"))
        .expect("fixture segment");
    let opened = Segment::open(&seg_path, tmp.path());
    if FORMAT_VERSION != 2 {
        assert!(matches!(opened, Err(SegmentError::Version(2))), "a format bump must reject the old segment");
        return;
    }
    let seg = opened.expect("format-2 segment written before wave R must open");
    let (graph, mem) = graph();
    assert_eq!(seg.nodes(), graph.nodes.as_slice(), "node table (labels, languages) decodes identically");
    assert_eq!(seg.files(), graph.files.as_slice());
    assert_eq!(seg.module_of(0), None, "no files.modules component before wave R");
    assert_eq!(seg.meta().edge_count as usize, graph.edges.len());
    for e in &graph.edges {
        let out = seg.out_edges(e.src, Some(e.kind));
        let hit = out.iter().find(|r| r.other == e.dst).unwrap_or_else(|| panic!("missing edge {e:?}"));
        assert_eq!(hit.meta, e.meta, "edge meta (strategy) decodes identically");
    }
    for (f, file) in graph.files.iter().enumerate() {
        assert_eq!(seg.content(f as u32).unwrap(), mem.0[&file.path]);
    }
    for label in SYMBOL_LABELS {
        let hits = seg
            .search_symbols(&SymbolQuery {
                text: format!("compat{label}"),
                labels: vec![label],
                limit: 5,
                ..SymbolQuery::default()
            })
            .unwrap();
        let top = hits.first().unwrap_or_else(|| panic!("no hit for {label}"));
        assert_eq!(seg.node(top.node).label, label);
    }
    for lang in LANGUAGES {
        let hits = seg
            .search_symbols(&SymbolQuery {
                text: "compat".into(),
                labels: SYMBOL_LABELS.to_vec(),
                language: Some(lang),
                limit: 50,
                ..SymbolQuery::default()
            })
            .unwrap();
        assert!(!hits.is_empty() && hits.iter().all(|h| seg.node(h.node).language == Some(lang)), "{lang}");
    }
}

/// What wave R adds to a segment without a format bump: the `Contract`
/// strategy (code 7), the appended labels and languages, and the optional
/// `files.modules` component.
#[test]
fn wave_r_additions_round_trip() {
    let (mut graph, mem) = graph();
    let first = first_symbol_node(&graph);
    graph.nodes[first].label = Label::Key;
    graph.nodes[first + 1].label = Label::Image;
    graph.files[0].language = Some(Language::Java);
    graph.nodes[graph.files[0].node as usize].language = Some(Language::Java);
    graph.edges[1].meta.strategy = Strategy::Contract;
    graph.modules = (0..graph.files.len()).map(|i| format!("module{i}")).collect();
    let store = tempfile::tempdir().unwrap();
    let meta = write_segment(&graph, &mem, store.path()).unwrap();
    let seg = Segment::open(&store.path().join("segments").join(format!("{}.rcseg", meta.id)), store.path()).unwrap();
    assert_eq!(seg.nodes(), graph.nodes.as_slice());
    assert_eq!(seg.files(), graph.files.as_slice());
    assert_eq!(seg.module_of(2), Some("module2"));
    assert_eq!(seg.module_of(99), None);
    let e = &graph.edges[1];
    let hit = seg.out_edges(e.src, Some(e.kind)).into_iter().find(|r| r.other == e.dst).unwrap();
    assert_eq!(hit.meta.strategy, Strategy::Contract);
}

fn first_symbol_node(graph: &ResolvedGraph) -> usize {
    graph.nodes.iter().position(|n| n.span.is_some()).unwrap()
}
