/// Whether `name` (folded) is a built-in function.
pub fn is_function(name: &str) -> bool {
    FUNCTIONS.binary_search(&name).is_ok()
}

/// Whether `name` (folded) is a type name.
pub fn is_type(name: &str) -> bool {
    TYPES.contains(&name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sorted_for_binary_search() {
        assert!(FUNCTIONS.windows(2).all(|w| w[0] < w[1]), "{:?}", FUNCTIONS.windows(2).find(|w| w[0] >= w[1]));
        assert!(is_function("count") && is_function("coalesce") && !is_function("film_in_stock"));
    }
}
