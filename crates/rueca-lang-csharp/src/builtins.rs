//! Names the resolver must never fuzzy-match to project symbols.
//!
//! - **C# keyword types** (`int`, `string`, `object`, `dynamic`, …) and
//!   the operators that look like calls (`nameof`, `typeof`, `sizeof`,
//!   `default`).
//! - **Namespace heads of the .NET libraries** (`System`, `Microsoft`,
//!   `Windows`), so that fully qualified uses
//!   (`System.IO.File.Exists(…)`) stop as external. A project namespace
//!   with the same head is still found first (the resolver tries the
//!   project's namespaces before this list).
//! - **Common base class library types** of `System`, `System.IO`,
//!   `System.Text`, `System.Threading(.Tasks)`, `System.Collections(.Generic,
//!   .Concurrent, .Immutable)`, `System.Linq`, `System.Net.Http`,
//!   `System.Text.Json`, `System.Text.RegularExpressions`,
//!   `System.Reflection`, `System.Diagnostics` and `System.Globalization`.
//!   They come from the SDK's implicit usings or explicit `using System…`,
//!   so a reference that reaches the unique-name rung is a library use,
//!   never a project symbol. Project types with the same name are still
//!   found first through usings and the namespace.
//! - **Methods every object, collection, LINQ sequence, string or task
//!   has** (`ToString`, `Equals`, `Add`, `Select`, `ConfigureAwait`, …):
//!   the resolver's unique-method rung would otherwise link every
//!   `list.Add(x)` on an untyped receiver to the only project method named
//!   `Add`. Typed receivers (`$type:T`) and implicit `this` still resolve
//!   them.
//!
//! Sorted for binary search (checked by a test).

