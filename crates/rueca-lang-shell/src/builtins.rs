/// Shell builtins, keywords and common utilities (never project symbols).
pub(crate) fn is_builtin(name: &str) -> bool {
    SHELL_BUILTINS.contains(&name) || UTILITIES.contains(&name)
}

/// Variables maintained by the shell (never environment reads).
pub(crate) fn is_shell_variable(name: &str) -> bool {
    SHELL_VARIABLES.contains(&name) || name.starts_with("BASH_") || name.starts_with("ZSH_")
}

/// An environment variable name by convention: upper case letters,
/// digits and `_`, starting with a letter or `_`, not maintained by the
/// shell.
pub(crate) fn is_env_name(name: &str) -> bool {
    let mut chars = name.chars();
    chars.next().is_some_and(|c| c.is_ascii_uppercase() || c == '_')
        && name.chars().any(|c| c.is_ascii_uppercase())
        && chars.all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_')
        && !is_shell_variable(name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names() {
        assert!(is_builtin("echo") && is_builtin("[[") && is_builtin("zstyle") && is_builtin("grep"));
        assert!(!is_builtin("deploy") && !is_builtin("nvm_ls"));
        assert!(is_env_name("HOME") && is_env_name("DATABASE_URL") && is_env_name("_PRIVATE_X"));
        assert!(!is_env_name("home") && !is_env_name("Path") && !is_env_name("BASH_SOURCE"));
        assert!(!is_env_name("LINENO") && !is_env_name("1") && !is_env_name("_") && !is_env_name("ZSH_CUSTOM"));
    }
}
