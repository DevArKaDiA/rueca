//! Rust module semantics and `impl` blocks (the Rust family).
//!
//! The pack (`rueca-lang-rust` crate docs) writes Rust's facts in the
//! generic vocabulary; this module gives them Rust's meaning where the
//! generic rules differ:
//!
//! - **Module lookups.** A name in a Rust module is one of its items (top
//!   level of the file; items of an `impl` block are not module names), else
//!   what its declarations bind, in order: `mod x;` (the module file),
//!   `extern crate`, `use` leaves (private ones too: the module and its
//!   descendants see them) and path anchors, then its glob imports
//!   (`use m::*`), then a child module file no `mod` binds (a `mod x;`
//!   generated by a macro the pack does not open; one written in a body
//!   the macro passes through, `cfg_net! { mod tcp; }`, is a declaration).
//!   A `use` path is resolved from its anchor — the crate root (`crate`),
//!   the file's module or an ancestor (`self` / `super`), a name the file
//!   binds (uniform paths), else a crate of the snapshot — and then walked
//!   segment by segment through module files (`mod` declarations),
//!   inline modules, types (associated items, enum variants) and
//!   re-exports. The file's binding environment holds every name its
//!   declarations bind; a glob binds the visible names of its target.
//! - **Two namespaces.** Modules and types live in one, functions,
//!   constants, statics and constructors (tuple and unit structs, variants)
//!   in the other, so one module may bind a name twice: `mod sleep; pub use
//!   sleep::sleep;`, or `mod x;` next to `fn x`. A lookup is for one of
//!   them: a call or a read wants a value, a type reference and every path
//!   segment before the last want a module or type. Among the candidates
//!   above, in their order, it takes the first of its namespace, else the
//!   first of the other one (a name the project only has there). A `use`
//!   leaf binds what its name names in both (the leaf is resolved again per
//!   namespace: the file has a binding environment per namespace), and a
//!   bare name prefers an import binding of its namespace, then an item of
//!   the module of its namespace.
//! - **Types bind in scope.** A type is the one the file declares,
//!   imports (globs and re-export chains included) or names by path; by
//!   name alone only in the file's own crate, never a same-named type of
//!   another crate (another repository's in an organization's joint
//!   resolve: tokio's `TcpStream` is not mio's), and a call result typed
//!   from a callee of another crate matched by name alone types nothing.
//!   So an `impl` attaches to the type its file sees, and a trait the file
//!   cannot see (a glob of `std`) is not another crate's same-named trait.
//!   When several crates' impls give a type members of one name (`impl
//!   From<ReasonPhrase> for Bytes` in hyper), the type's own crate's come
//!   first (`bytes`'s `Bytes::from`).
//! - **Test doubles never bind** for other code: definitions of a
//!   `#[cfg(test)]` module are test code — inline ones from the pack, module
//!   files declared by `#[cfg(test)] mod x;` (and the files below them)
//!   through the pack's `$test` marker import — so they leave the by-name
//!   index, and a module lookup takes a test binding only when nothing else
//!   binds the name (`#[cfg(test)] use mocks::spawn_blocking;` next to the
//!   real import). One definition twice (`#[cfg]` variants of one module,
//!   same label and qualified name) counts once in by-name matches.
//! - **`IMPORTS`** go from a file to the module file each `use` leaf (or
//!   glob) is found in, to the file a `mod x;` names and to the root of an
//!   `extern crate`; the synthetic imports of path anchors make none.
//! - **Inline modules** (`Module` definitions) own their items: `m::f` and
//!   `tests.helper` are member lookups, which also see the names a `use`
//!   inside the module binds (`mod facade { pub use crate::engine::work; }`;
//!   the pack marks such imports `$in:<module>`). The file's binding
//!   environment includes those imports too (code in an inline module is
//!   resolved with the file's environment).
//! - **`impl` items** (a definition whose `bases` is the self type of its
//!   `impl` block) are attached to the type their `bases` names, resolved
//!   like a type reference in the item's outer scope, wherever the type is
//!   declared; `$self` / `$member:` receivers inside them use that type. An
//!   `impl Tr for T` adds `IMPLEMENTS` `T` → `Tr` (the strategy and
//!   confidence of resolving `Tr`), makes `Tr` a base of `T` (default
//!   methods are found through `T`), and gives each item `OVERRIDES` to the
//!   trait's item with its name (`type_resolved` 0.90). A trait outside the
//!   project makes `T` open: a member missing from it is external (an
//!   `Iterator` adaptor on a type implementing `Iterator`).
//! - **Blanket impls** (`impl<T: Bound> Tr for T`, base `<T>`): the items
//!   override the trait's and are the targets of by-name calls of their
//!   name (they apply to every type). An impl on `&T`, `&mut T` or `Box<T>`
//!   (base `<&T>`) forwards to `T`'s impl and counts as the trait's item.
//! - **Call results** (`$ret:<receiver>#<name>[?]`, the value a call
//!   returns, see `rueca-lang-rust`): the callee is resolved like a call,
//!   its signature's return type (`Self` = its impl's type or trait;
//!   `Result<T, _>` / `Option<T>` → `T` when unwrapped by `?`, `unwrap()`,
//!   `expect()`; references and smart pointers seen through) is resolved
//!   in the callee's file, and the member is looked up in it
//!   (`type_resolved` 0.85). A callee or return type outside the project
//!   makes the call external.
//! - **Methods by name** (a call whose receiver type is unknown): the
//!   implementations of one trait method count as that trait method, so a
//!   name that only one trait declares (implemented anywhere) resolves to
//!   the trait's method (`heuristic` 0.50); several distinct candidates are
//!   no edge (as the Go and C/C++ unique-method rung). Names of common
//!   standard-library methods (`unwrap`, `iter`, `insert`, …) never match by
//!   name: such calls are far more often on standard types, and are counted
//!   as external.
//! - Rust types have no constructors (`T::new` is an ordinary associated
//!   function), and are open: a member missing from one is external (a
//!   derive, a blanket implementation, an associated type of a foreign
//!   trait), as is a method call on an unknown receiver whose name no
//!   project method has.
//! - **Macros by name**: a bare call that no rung resolves is the only
//!   `macro_rules!` with that name in the snapshot, test code included
//!   (`#[macro_use]` makes macros visible without imports), `unique_name`
//!   0.60.

