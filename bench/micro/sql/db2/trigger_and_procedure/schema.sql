CREATE TABLE actor (
  actor_id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1),
  last_name VARCHAR(45) NOT NULL,
  last_update DATE,
  CONSTRAINT pk_actor PRIMARY KEY (actor_id)
)@

CREATE TABLE actor_audit (
  actor_id INT NOT NULL,
  changed DATE,
  CONSTRAINT fk_audit_actor FOREIGN KEY (actor_id) REFERENCES actor (actor_id)
)@

CREATE OR REPLACE TRIGGER actor_before_update
BEFORE UPDATE ON actor
REFERENCING NEW AS new
FOR EACH ROW
BEGIN
  SET new.last_update = current_date;
END@

CREATE PROCEDURE record_change (IN p_actor INT)
LANGUAGE SQL
BEGIN
  INSERT INTO actor_audit (actor_id, changed) VALUES (p_actor, CURRENT DATE);
END@

CREATE PROCEDURE rename_actor (IN p_actor INT, IN p_name VARCHAR(45))
LANGUAGE SQL
BEGIN
  DECLARE v_found INT DEFAULT 0;
  SELECT COUNT(*) INTO v_found FROM actor WHERE actor_id = p_actor;
  IF v_found > 0 THEN
    UPDATE actor SET last_name = p_name WHERE actor_id = p_actor;
    CALL record_change(p_actor);
  END IF;
END@

CREATE VIEW actor_changes AS
SELECT a.actor_id, a.last_name, u.changed FROM actor a JOIN actor_audit u ON u.actor_id = a.actor_id@
