"""Dataset download (pinned HF revisions, sha256-verified) and S1 instance selection."""

from __future__ import annotations

import csv
import sys
import urllib.request
from pathlib import Path

import pyarrow.parquet as pq

from .common import DATASETS_DIR, MANIFEST_PATH, candidate_path, load_manifest, log, sha256_file, stable_key
from .gold import parse_patch

GENERATED_MARKER = "# --- generated by `telar-bench select`; do not edit below this line ---"


def dataset_path(key: str) -> Path:
    cfg = load_manifest()["datasets"][key]
    return DATASETS_DIR / f"{key}{Path(cfg['file']).suffix}"


def fetch_dataset(key: str) -> Path:
    cfg = load_manifest()["datasets"][key]
    dest = dataset_path(key)
    if dest.exists() and sha256_file(dest) == cfg["sha256"]:
        return dest
    DATASETS_DIR.mkdir(parents=True, exist_ok=True)
    url = f"https://huggingface.co/datasets/{cfg['hf']}/resolve/{cfg['revision']}/{cfg['file']}"
    log(f"download {cfg['hf']}@{cfg['revision'][:10]}")
    tmp = dest.with_suffix(".part")
    urllib.request.urlretrieve(url, tmp)
    got = sha256_file(tmp)
    if got != cfg["sha256"]:
        tmp.unlink()
        raise RuntimeError(f"sha256 mismatch for {key}: {got} != {cfg['sha256']}")
    tmp.replace(dest)
    return dest


_COLS = ("instance_id", "repo", "base_commit", "patch", "problem_statement")


def load_rows(key: str) -> list[dict]:
    """Rows of a pinned dataset. Source datasets expose `_COLS` (+ `language`
    and the manifest `gold_column` when present); assembled-gold datasets
    declare their own `columns` and an optional `id_column`."""
    cfg = load_manifest()["datasets"][key]
    path = fetch_dataset(key)
    id_col = cfg.get("id_column", "instance_id")
    wanted = list(cfg.get("columns", _COLS)) + ["language"] + ([cfg["gold_column"]] if cfg.get("gold_column") else [])
    if path.suffix == ".parquet":
        names = set(pq.read_schema(path).names)
        rows = pq.read_table(path, columns=[c for c in dict.fromkeys(wanted) if c in names]).to_pylist()
    else:
        csv.field_size_limit(sys.maxsize)
        with path.open(newline="", encoding="utf-8") as fh:
            rows = [{c: r.get(c) for c in wanted if c in r} for r in csv.DictReader(fh)]
    if id_col != "instance_id":
        for r in rows:
            r["instance_id"] = r.get(id_col)
    return rows


_ROWS_CACHE: dict[str, dict[str, dict]] = {}


def rows_by_id(key: str) -> dict[str, dict]:
    if key not in _ROWS_CACHE:
        _ROWS_CACHE[key] = {r["instance_id"]: r for r in load_rows(key)}
    return _ROWS_CACHE[key]


def _eligible(patch: str, language: str) -> bool:
    for fp in parse_patch(patch or ""):
        if fp.old_path and candidate_path(fp.old_path, language):
            return True
    return False


_LANG_NORM = {"typescript": "typescript", "javascript": "javascript", "python": "python"}


def _row_language(row: dict, default: str) -> str:
    lang = str(row.get("language") or "").strip().lower()
    return _LANG_NORM.get(lang, default)


def gold_assets(iid: str, row: dict, src: str) -> list[str]:
    """Assembled gold available for an instance (selection priority + report)."""
    man = load_manifest()
    out = []
    gcol = man["datasets"][src].get("gold_column")
    if gcol and str(row.get(gcol) or "").strip() not in ("", "[]"):
        out.append(f"{src}:{gcol}")
    for key in man["s1"].get("gold_assets", []):
        if iid in rows_by_id(key):
            out.append(key)
    return out


def select_instances() -> list[dict]:
    man = load_manifest()
    chosen: list[dict] = []
    for spec in man["s1"]["repos"]:
        cands: dict[str, dict] = {}
        for src in spec["sources"]:
            for iid, r in rows_by_id(src).items():
                if r["repo"] != spec["repo"] or iid in cands:
                    continue
                if not _eligible(r["patch"], spec["language"]):
                    continue
                cands[iid] = {
                    "id": iid,
                    "repo": r["repo"],
                    "language": _row_language(r, spec["language"]),
                    "base_commit": r["base_commit"],
                    "dataset": src,
                    "assets": gold_assets(iid, r, src),
                }
        ordered = sorted(cands.values(), key=lambda c: (-len(c["assets"]), stable_key(c["id"])))
        picked = ordered[: spec["quota"]]
        n_assets = sum(1 for c in picked if c["assets"])
        log(f"select {spec['repo']}: {len(picked)}/{len(ordered)} eligible, {n_assets} with assembled gold")
        chosen.extend(picked)
    return chosen


def write_instances(instances: list[dict]) -> None:
    text = MANIFEST_PATH.read_text()
    head = text.split(GENERATED_MARKER)[0].rstrip() + "\n\n" + GENERATED_MARKER + "\n"
    lines = []
    for inst in instances:
        lines.append("\n[[s1.instances]]")
        for k in ("id", "repo", "language", "base_commit", "dataset"):
            lines.append(f'{k} = "{inst[k]}"')
        lines.append("assets = [" + ", ".join(f'"{a}"' for a in inst.get("assets", [])) + "]")
    MANIFEST_PATH.write_text(head + "\n".join(lines).lstrip("\n") + "\n")


def instance_row(inst: dict) -> dict:
    return rows_by_id(inst["dataset"])[inst["id"]]
