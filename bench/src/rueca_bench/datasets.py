"""Dataset download (pinned HF revisions, sha256-verified) and S1 instance selection."""

from __future__ import annotations

import csv
import json
import sys
import urllib.request
from pathlib import Path

import pyarrow.parquet as pq

from .common import DATASETS_DIR, MANIFEST_PATH, candidate_path, lang_family, load_manifest, log, pinned_asset, sha256_file, stable_key
from .gold import parse_patch

GENERATED_MARKER = "# --- generated by `rueca-bench select`; do not edit below this line ---"


def dataset_path(key: str) -> Path:
    """One file per dataset (`file` + `sha256`), or a directory for datasets
    pinned as several files (`files = { "<path in repo>" = "<sha256>" }`,
    e.g. Multi-SWE-bench's one JSONL per repository)."""
    cfg = load_manifest()["datasets"][key]
    if "files" in cfg:
        return DATASETS_DIR / key
    return DATASETS_DIR / f"{key}{Path(cfg['file']).suffix}"


def _fetch_file(cfg: dict, key: str, remote: str, dest: Path, sha256: str) -> Path:
    found = pinned_asset(dest, sha256)
    if found != dest:
        return found
    if dest.exists() and sha256_file(dest) == sha256:
        return dest
    dest.parent.mkdir(parents=True, exist_ok=True)
    url = f"https://huggingface.co/datasets/{cfg['hf']}/resolve/{cfg['revision']}/{remote}"
    log(f"download {cfg['hf']}@{cfg['revision'][:10]} {remote}")
    tmp = dest.with_suffix(dest.suffix + ".part")
    urllib.request.urlretrieve(url, tmp)
    got = sha256_file(tmp)
    if got != sha256:
        tmp.unlink()
        raise RuntimeError(f"sha256 mismatch for {key} {remote}: {got} != {sha256}")
    tmp.replace(dest)
    return dest


def fetch_dataset(key: str) -> Path:
    cfg = load_manifest()["datasets"][key]
    dest = dataset_path(key)
    if "files" in cfg:
        for remote, sha in cfg["files"].items():
            _fetch_file(cfg, key, remote, dest / Path(remote).name, sha)
        return dest
    return _fetch_file(cfg, key, cfg["file"], dest, cfg["sha256"])


def _dataset_files(key: str) -> list[Path]:
    """Local paths of every file of a multi-file dataset (shared cache honoured)."""
    cfg = load_manifest()["datasets"][key]
    fetch_dataset(key)
    return [pinned_asset(dataset_path(key) / Path(r).name, sha) for r, sha in cfg["files"].items()]


def _multi_swe_bench_rows(key: str) -> list[dict]:
    """Multi-SWE-bench JSONL -> the SWE-bench columns the harness uses:
    `instance_id` (`org__repo-number`), `repo`, `base_commit` (`base.sha`),
    `patch` (`fix_patch`) and `problem_statement` (title and body of each
    resolved issue, as in SWE-bench)."""
    rows = []
    for path in _dataset_files(key):
        with path.open(encoding="utf-8") as fh:
            for line in fh:
                if not line.strip():
                    continue
                r = json.loads(line)
                issues = r.get("resolved_issues") or []
                text = "\n\n".join(f"{i.get('title') or ''}\n{i.get('body') or ''}".strip() for i in issues)
                rows.append(
                    {
                        "instance_id": r.get("instance_id") or f"{r['org']}__{r['repo']}-{r['number']}",
                        "repo": f"{r['org']}/{r['repo']}",
                        "base_commit": r["base"]["sha"],
                        "patch": r.get("fix_patch") or "",
                        "problem_statement": text or f"{r.get('title') or ''}\n{r.get('body') or ''}",
                    }
                )
    return rows


_COLS = ("instance_id", "repo", "base_commit", "patch", "problem_statement")


def _dotted(row: dict, path: str):
    cur = row
    for part in path.split("."):
        if not isinstance(cur, dict):
            return None
        cur = cur.get(part)
    return cur


def load_rows(key: str) -> list[dict]:
    """Rows of a pinned dataset. Source datasets expose `_COLS` (+ `language`
    and the manifest `gold_column` when present); assembled-gold datasets
    declare their own `columns` and an optional `id_column`. An optional
    `row_filter = { "dotted.column.path" = [allowed values] }` keeps only
    matching rows (e.g. SWE-rebench V2's own LLM quality screen)."""
    cfg = load_manifest()["datasets"][key]
    if cfg.get("format") == "multi_swe_bench":
        return _multi_swe_bench_rows(key)
    path = fetch_dataset(key)
    id_col = cfg.get("id_column", "instance_id")
    row_filter: dict = cfg.get("row_filter", {})
    filter_cols = [k.split(".", 1)[0] for k in row_filter]
    wanted = list(cfg.get("columns", _COLS)) + ["language"] + ([cfg["gold_column"]] if cfg.get("gold_column") else []) + filter_cols
    if path.suffix == ".parquet":
        names = set(pq.read_schema(path).names)
        filters = None
        if cfg.get("filter_repos"):
            # large multi-language datasets: read only the S1 repositories sourced from it
            repos = sorted({r["repo"] for r in load_manifest()["s1"]["repos"] if key in r["sources"]})
            filters = [("repo", "in", repos)]
        rows = pq.read_table(path, columns=[c for c in dict.fromkeys(wanted) if c in names], filters=filters).to_pylist()
    else:
        csv.field_size_limit(sys.maxsize)
        with path.open(newline="", encoding="utf-8") as fh:
            rows = [{c: r.get(c) for c in wanted if c in r} for r in csv.DictReader(fh)]
    if row_filter:
        rows = [r for r in rows if all(_dotted(r, k) in allowed for k, allowed in row_filter.items())]
        for r in rows:
            for c in filter_cols:
                r.pop(c, None)
    if id_col != "instance_id":
        for r in rows:
            r["instance_id"] = r.get(id_col)
    return rows


_ROWS_CACHE: dict[str, dict[str, dict]] = {}


def rows_by_id(key: str) -> dict[str, dict]:
    if key not in _ROWS_CACHE:
        _ROWS_CACHE[key] = {r["instance_id"]: r for r in load_rows(key)}
    return _ROWS_CACHE[key]


def _eligible(patch: str, language: str) -> bool:
    for fp in parse_patch(patch or ""):
        if fp.old_path and candidate_path(fp.old_path, language):
            return True
    return False


_LANG_NORM = {"typescript": "typescript", "javascript": "javascript", "python": "python", "php": "php", "go": "go", "java": "java", "c": "c", "c++": "cpp", "cpp": "cpp"}


def _row_language(row: dict, default: str) -> str:
    lang = str(row.get("language") or "").strip().lower()
    return _LANG_NORM.get(lang, default)


def gold_assets(iid: str, row: dict, src: str) -> list[str]:
    """Assembled gold available for an instance (selection priority + report)."""
    man = load_manifest()
    out = []
    gcol = man["datasets"][src].get("gold_column")
    if gcol and str(row.get(gcol) or "").strip() not in ("", "[]"):
        out.append(f"{src}:{gcol}")
    for key in man["s1"].get("gold_assets", []):
        if iid in rows_by_id(key):
            out.append(key)
    return out


def select_instances(languages: set[str] | None = None) -> list[dict]:
    """Instances of every `[[s1.repos]]` entry (or only those of the given
    language families), in manifest order. Inside a repository: more
    assembled gold first, then — when the entry sets `source_priority = true`
    — earlier `sources` first (e.g. human-validated SWE-bench Multilingual
    before a supplement), then sha256(instance_id)."""
    man = load_manifest()
    chosen: list[dict] = []
    for spec in man["s1"]["repos"]:
        if languages and lang_family(spec["language"]) not in languages:
            continue
        cands: dict[str, dict] = {}
        for src in spec["sources"]:
            for iid, r in rows_by_id(src).items():
                if r["repo"] != spec["repo"] or iid in cands:
                    continue
                if not _eligible(r["patch"], spec["language"]):
                    continue
                cands[iid] = {
                    "id": iid,
                    "repo": r["repo"],
                    "language": _row_language(r, spec["language"]),
                    "base_commit": r["base_commit"],
                    "dataset": src,
                    "assets": gold_assets(iid, r, src),
                }
        prio = {src: i for i, src in enumerate(spec["sources"])} if spec.get("source_priority") else {}
        ordered = sorted(cands.values(), key=lambda c: (-len(c["assets"]), prio.get(c["dataset"], 0), stable_key(c["id"])))
        picked = ordered[: spec["quota"]]
        n_assets = sum(1 for c in picked if c["assets"])
        log(f"select {spec['repo']}: {len(picked)}/{len(ordered)} eligible, {n_assets} with assembled gold")
        chosen.extend(picked)
    return chosen


def merge_instances(existing: list[dict], selected: list[dict], languages: set[str] | None) -> list[dict]:
    """Selected instances replace those of their language families; other
    families keep their existing entries. Order: manifest `[[s1.repos]]`
    order, then each repository's selection order, so a partial
    re-selection never moves another language's instances."""
    if not languages:
        return selected
    keep = [i for i in existing if lang_family(i["language"]) not in languages]
    by_repo: dict[str, list[dict]] = {}
    for i in keep + selected:
        by_repo.setdefault(i["repo"], []).append(i)
    out: list[dict] = []
    for spec in load_manifest()["s1"]["repos"]:
        out.extend(by_repo.pop(spec["repo"], []))
    for rest in by_repo.values():
        out.extend(rest)
    return out


def write_instances(instances: list[dict]) -> None:
    text = MANIFEST_PATH.read_text()
    head = text.split(GENERATED_MARKER)[0].rstrip() + "\n\n" + GENERATED_MARKER + "\n"
    lines = []
    for inst in instances:
        lines.append("\n[[s1.instances]]")
        for k in ("id", "repo", "language", "base_commit", "dataset"):
            lines.append(f'{k} = "{inst[k]}"')
        lines.append("assets = [" + ", ".join(f'"{a}"' for a in inst.get("assets", [])) + "]")
    MANIFEST_PATH.write_text(head + "\n".join(lines).lstrip("\n") + "\n")


def instance_row(inst: dict) -> dict:
    return rows_by_id(inst["dataset"])[inst["id"]]
